#!/usr/bin/env node
/**
 * Vendor tesseract.js into extension/assets/tesseract/.
 *
 * WHY THIS EXISTS: MV3 forbids remotely hosted code. tesseract.js normally
 * pulls its WASM core, its worker, and eng.traineddata from a CDN at runtime.
 * An extension that does that violates the policy and breaks offline — which
 * would be absurd for a product whose whole pitch is running locally.
 *
 *   npm run vendor:tesseract
 *
 * The vendored files are ~15 MB. They are gitignored; every teammate must run
 * this once before the vision pipeline works.
 */

import { mkdir, writeFile, readFile, access } from 'node:fs/promises';
import { fileURLToPath, URL } from 'node:url';
import { dirname, resolve } from 'node:path';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEST = resolve(REPO, 'extension/assets/tesseract');

const Y = '\x1b[33m', G = '\x1b[32m', R = '\x1b[31m', B = '\x1b[1m', D = '\x1b[2m', X = '\x1b[0m';

console.log(`${B}Vendoring tesseract.js into extension/assets/tesseract/${X}\n`);

await mkdir(DEST, { recursive: true });

// --- tesseract.js core -----------------------------------------------------
// Pinned version so every teammate gets identical OCR output.
const VERSION = '6.0.1';

const CDN = {
  'tesseract.min.js': `https://cdn.jsdelivr.net/npm/tesseract.js@${VERSION}/dist/tesseract.min.js`,
  'worker.min.js': `https://cdn.jsdelivr.net/npm/tesseract.js@${VERSION}/dist/worker.min.js`,
  'tesseract-core-simd.wasm.js': `https://cdn.jsdelivr.net/npm/tesseract.js-core@${VERSION}/tesseract-core-simd.wasm.js`,
  'tesseract-core.wasm.js': `https://cdn.jsdelivr.net/npm/tesseract.js-core@${VERSION}/tesseract-core.wasm.js`,
  'eng.traineddata.gz': 'https://tessdata.projectnaptha.com/4.0.0/eng.traineddata.gz',
};

let failures = 0;

for (const [name, url] of Object.entries(CDN)) {
  try {
    process.stdout.write(`  fetching ${D(name)}… `);
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);

    const buf = Buffer.from(await res.arrayBuffer());
    await writeFile(resolve(DEST, name), buf);
    console.log(`${G}✓${X} ${D}${(buf.length / 1e6).toFixed(1)} MB${X}`);
  } catch (err) {
    failures++;
    console.log(`${R}✗${X} ${err.message}`);
    console.log(`    ${D}${url}${X}`);
  }
}

// --- entry module ----------------------------------------------------------
// lib/vision-redact.js imports this, because a bare `import 'tesseract.js'`
// specifier cannot resolve in an unbundled MV3 extension.
const entry = `/**
 * Vendored tesseract.js entry point.
 * GENERATED by scripts/vendor-tesseract.js — do not edit.
 *
 * tesseract.js's default export constructs a worker. All three asset paths are
 * local so nothing is fetched from a CDN at runtime.
 */
import Tesseract from './tesseract.min.js';

export default Tesseract;
export const LOCAL_ASSETS = {
  workerPath: './worker.min.js',
  corePath: './',
  langPath: './',
};
`;

await writeFile(resolve(DEST, 'entry.js'), entry);
console.log(`\n  ${G}✓${X} wrote entry.js`);

// --- manifest --------------------------------------------------------------
const manifest = {
  note: 'Generated. See scripts/vendor-tesseract.js',
  tesseractJs: VERSION,
  files: Object.keys(CDN),
};
await writeFile(resolve(DEST, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

console.log('');
if (failures) {
  console.log(`${R}${failures} file(s) failed to download.${X}`);
  console.log(`${D}Check your network and retry. The vision pipeline (Phase 5) will fall back${X}`);
  console.log(`${D}to a model-level warning until these land.${X}\n`);
  process.exit(1);
}

console.log(`${G}Done.${X} extension/assets/tesseract/ is now self-contained.`);
console.log(`${D}~15 MB, gitignored. Every teammate must run this before Phase 5.${X}\n`);

function D(s) { return `\x1b[2m${s}${X}`; }